export type Strings = typeof en;
export type StringKey = { [K in keyof Strings]: Strings[K] extends string ? K : never }[keyof Strings];
/** Shape every language file must match: same keys, string (or string list) values. */
export type Dictionary = { [K in keyof Strings]: Strings[K] extends readonly string[] ? readonly string[] : string };

const dictionaries: Record<Language, Dictionary> = { en, hi, mr };

/** The active language's dictionary (lists such as `limitations` included). */
export const strings = (): Dictionary => dictionaries[getLanguage()];

/** Look up a string in the active language and fill {placeholders}. Unknown placeholders are left as-is. */
export function t(key: StringKey, params?: Record<string, string | number>): string {
  const template = (dictionaries[getLanguage()][key] as string | undefined) ?? (en[key] as string);
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    params[name] === undefined ? m : String(params[name]),
  );
}
